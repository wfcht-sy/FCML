#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Loss Function Ablation Experiment Plot.

Reads the three curve CSV files generated by run_backbone_ablation.py and
produces a side-by-side comparison figure showing:
  - Validation MSE convergence for all three groups (log scale)
  - A bar chart of the best val_mse per group

All groups use the official Neural-Fly Phi_Net backbone (PhiNetworkFCML).
The only variable is the training paradigm (loss function).

Output: figures/fig_backbone_ablation.png
"""

import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.ticker as ticker
import numpy as np
import os
import sys
import warnings

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..')))
from config import TRAINING_DIR, FIGURES_DIR

warnings.filterwarnings("ignore", category=UserWarning)

ABLATION_DIR = os.path.join(TRAINING_DIR, "backbone_ablation")
os.makedirs(FIGURES_DIR, exist_ok=True)

# ── Group definitions ──────────────────────────────────────────────────────
GROUPS = [
    {
        "key":    "nf_daiml",
        "label":  "[A] NF baseline\n(official Phi_Net + DAIML)",
        "color":  "#1f77b4",
        "ls":     "--",
        "lw":     2.0,
    },
    {
        "key":    "ours_no_triplet",
        "label":  "[B] FCML w/o Triplet\n(official Phi_Net + MSE only)",
        "color":  "#ff7f0e",
        "ls":     "-.",
        "lw":     2.0,
    },
    {
        "key":    "ours_full",
        "label":  "[D] FCML (Ours)\n(official Phi_Net + DTW-Triplet)",
        "color":  "#d62728",
        "ls":     "-",
        "lw":     2.5,
    },
]


def load_curves():
    """Load and validate the three CSV files. Returns a dict of DataFrames."""
    curves = {}
    missing = []
    for g in GROUPS:
        path = os.path.join(ABLATION_DIR, f"curve_{g['key']}.csv")
        if not os.path.exists(path):
            missing.append(path)
            continue
        df = pd.read_csv(path)
        if 'val_mse' in df.columns:
            curves[g["key"]] = df.dropna(subset=["val_mse"])
        elif 'val_score' in df.columns:
            df = df.dropna(subset=["val_score"]).copy()
            df["val_mse"] = df["val_score"]
            curves[g["key"]] = df
        else:
            print(f"  [WARNING] Neither 'val_mse' nor 'val_score' found in {path}")
    if missing:
        print("  [ERROR] Missing curve files:")
        for p in missing:
            print(f"    {p}")
        print("  Run: python scripts/offline/run_backbone_ablation.py")
    return curves


def plot_backbone_ablation():
    curves = load_curves()
    if not curves:
        return

    plt.rcParams["font.family"] = "DejaVu Sans"
    plt.rcParams["axes.unicode_minus"] = False

    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    fig.suptitle("Loss Function Ablation: Validation MSE Comparison", fontsize=15, fontweight="bold")

    # ── Left panel: convergence curves ────────────────────────────────────
    ax_curve = axes[0]
    for g in GROUPS:
        if g["key"] not in curves:
            continue
        df = curves[g["key"]]
        ax_curve.plot(
            df["epoch"], df["val_mse"],
            color=g["color"], linestyle=g["ls"], linewidth=g["lw"],
            label=g["label"], alpha=0.9
        )

    ax_curve.set_yscale("log")
    ax_curve.set_xlabel("Epoch", fontsize=12, fontweight="bold")
    ax_curve.set_ylabel("Validation MSE (log scale)", fontsize=12, fontweight="bold")
    ax_curve.set_title("Convergence Curves (unified backbone)", fontsize=13)
    ax_curve.grid(True, which="major", ls="-", alpha=0.5, color="gray")
    ax_curve.grid(True, which="minor", ls=":", alpha=0.3, color="gray")
    ax_curve.legend(fontsize=9, loc="upper right", framealpha=0.9, edgecolor="black")

    # ── Right panel: final best val_mse bar chart ──────────────────────────
    ax_bar = axes[1]
    labels, values, colors = [], [], []
    for g in GROUPS:
        if g["key"] not in curves:
            continue
        best_val = curves[g["key"]]["val_mse"].min()
        short_label = g["label"].split("\n")[0]
        labels.append(short_label)
        values.append(best_val)
        colors.append(g["color"])

    x = np.arange(len(labels))
    bars = ax_bar.bar(x, values, color=colors, width=0.55, edgecolor="black", linewidth=0.8)

    # Highlight our proposed method with a thicker border
    proposed_idx = next((i for i, g in enumerate(GROUPS) if g["key"] == "ours_full" and g["key"] in curves), None)
    if proposed_idx is not None:
        bars[proposed_idx].set_edgecolor("#d62728")
        bars[proposed_idx].set_linewidth(2.5)

    for i, (bar, val) in enumerate(zip(bars, values)):
        label_text = f"{val:.5f}"
        if proposed_idx is not None and i == proposed_idx:
            label_text += " †"
        ax_bar.text(
            bar.get_x() + bar.get_width() / 2,
            bar.get_height() * 1.03,
            label_text,
            ha="center", va="bottom", fontsize=9, fontweight="bold"
        )

    ax_bar.set_xticks(x)
    ax_bar.set_xticklabels(labels, fontsize=9)
    ax_bar.set_ylabel("Best Validation MSE", fontsize=12, fontweight="bold")
    ax_bar.set_title("Best Val MSE per Group", fontsize=13)
    ax_bar.yaxis.set_major_formatter(ticker.FormatStrFormatter("%.5f"))
    ax_bar.grid(True, axis="y", ls="--", alpha=0.5)
    # Footnote: explain offline vs online trade-off
    ax_bar.annotate(
        "† Our proposed method. DTW-Triplet trades a small offline MSE\n"
        "  for domain-invariant features that improve online adaptation.",
        xy=(0.01, 0.01), xycoords="axes fraction",
        fontsize=7.5, color="#555555",
        verticalalignment="bottom"
    )

    plt.tight_layout()
    out_path = os.path.join(FIGURES_DIR, "fig_backbone_ablation.png")
    plt.savefig(out_path, dpi=300, bbox_inches="tight")
    print(f"\n  Figure saved: {out_path}")

    # ── Print summary table ──────────────────────────────────────────
    all_vals = {g["key"]: curves[g["key"]]["val_mse"].min() for g in GROUPS if g["key"] in curves}
    best_key = min(all_vals, key=all_vals.get) if all_vals else None
    print("\n  ┌─────────────────────────────┬──────────────┐")
    print("  │ Group                       │ Best Val MSE │")
    print("  ├─────────────────────────────┼──────────────┤")
    for g in GROUPS:
        if g["key"] not in curves:
            print(f"  │ {g['key']:<27s} │   MISSING    │")
            continue
        best = curves[g["key"]]["val_mse"].min()
        marker = ""
        if g["key"] == best_key:
            marker = " ★"  # lowest offline MSE
        if g["key"] == "ours_full":
            marker += "†"  # our proposed method
        marker = (marker + "  ")[:3]  # fixed width
        print(f"  │ {g['label'].split(chr(10))[0]:<27s} │  {best:.6f} {marker}│")
    print("  └─────────────────────────────┴──────────────┘")
    print("  ★ = lowest offline val_mse   † = our proposed method")
    print("  Note: DTW-Triplet trades small offline MSE for domain-invariant")
    print("        features; online tracking performance is the primary metric.")


if __name__ == "__main__":
    plot_backbone_ablation()
